import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import Document from "../models/Document.js";
import KYC from "../models/KYC.js";
import LoanApplication from "../models/LoanApplication.js";
import FixedDeposit from "../models/FixedDeposit.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const uploadsDir = path.resolve(__dirname, "..", "uploads");

/**
 * Verifies whether an authenticated customer is the legitimate owner of the requested document file.
 * Checks Document records, KYC submissions, Loan Applications, and Fixed Deposit certificates.
 *
 * @param {string|import("mongoose").Types.ObjectId} userId
 * @param {string} safeFilename
 * @returns {Promise<boolean>}
 */
export const verifyCustomerDocumentOwnership = async (userId, safeFilename) => {
  if (!userId || !safeFilename) return false;

  const userIdStr = userId.toString();
  // 1. Fast check: filename strictly contains this customer's ID (generated by storage systems)
  if (safeFilename.includes(userIdStr)) {
    return true;
  }

  const escaped = safeFilename.replace(/[/\-\\^$*+?.()|[\]{}]/g, "\\$&");
  const filenameRegex = new RegExp(escaped, "i");

  // 2. Check Document collection
  const docMatch = await Document.findOne({
    user: userId,
    $or: [{ fileUrl: filenameRegex }, { publicId: safeFilename }],
  })
    .select("_id")
    .lean();
  if (docMatch) return true;

  // 3. Check KYC collection (documentUrl, panUrl, aadhaarUrl, selfieUrl)
  const kycMatch = await KYC.findOne({
    user: userId,
    $or: [
      { documentUrl: filenameRegex },
      { panUrl: filenameRegex },
      { aadhaarUrl: filenameRegex },
      { selfieUrl: filenameRegex },
    ],
  })
    .select("_id")
    .lean();
  if (kycMatch) return true;

  // 4. Check LoanApplication collection
  const loanMatch = await LoanApplication.findOne({
    user: userId,
    $or: [
      { "documents.panCardUrl": filenameRegex },
      { "documents.panCardFileName": filenameRegex },
      { "documents.aadhaarCardUrl": filenameRegex },
      { "documents.aadhaarCardFileName": filenameRegex },
      { "documents.salarySlipUrl": filenameRegex },
      { "documents.salarySlipFileName": filenameRegex },
      { "documents.bankStatementUrl": filenameRegex },
      { "documents.bankStatementFileName": filenameRegex },
      { "documents.specificDocs.docUrl": filenameRegex },
      { "documents.specificDocs.fileName": filenameRegex },
      { "documents.additionalDocs.docUrl": filenameRegex },
      { "documents.additionalDocs.fileName": filenameRegex },
    ],
  })
    .select("_id")
    .lean();
  if (loanMatch) return true;

  // 5. Check FixedDeposit collection (certificateUrl)
  const fdMatch = await FixedDeposit.findOne({
    user: userId,
    certificateUrl: filenameRegex,
  })
    .select("_id")
    .lean();
  if (fdMatch) return true;

  return false;
};

/**
 * Controller to securely serve uploaded files for preview and download.
 * Enforces:
 *  - Authentication (via protect middleware)
 *  - Role-based authorization: bank staff ('worker', 'admin') have access for review workflows
 *  - Strict customer ownership: customers can only access their own documents (no IDOR)
 *  - Path traversal protection
 *  - Strict 404 for missing files (never spoofed)
 */
export const serveSecureDocument = async (req, res) => {
  try {
    const rawParam = req.params.filename || req.params[0];
    if (!rawParam) {
      return res.status(404).json({ success: false, message: "Document not specified" });
    }

    let decodedFilename;
    try {
      decodedFilename = decodeURIComponent(rawParam);
    } catch {
      decodedFilename = rawParam;
    }

    const safeFilename = path.basename(decodedFilename);

    if (
      !safeFilename ||
      safeFilename === "." ||
      safeFilename === ".." ||
      safeFilename.includes("..") ||
      safeFilename.includes("/") ||
      safeFilename.includes("\\")
    ) {
      return res.status(400).json({ success: false, message: "Invalid document filename" });
    }

    const targetPath = path.resolve(uploadsDir, safeFilename);

    // Prevent path traversal outside the uploads directory
    if (!targetPath.startsWith(uploadsDir + path.sep) && targetPath !== uploadsDir) {
      return res.status(403).json({ success: false, message: "Invalid document path" });
    }

    // Role-based authorization & ownership checks
    const role = req.user?.role;
    const isStaff = role === "worker" || role === "admin";

    if (!isStaff) {
      // Customer: verify ownership
      const isOwner = await verifyCustomerDocumentOwnership(req.user?._id, safeFilename);
      if (!isOwner) {
        return res.status(403).json({
          success: false,
          message: "Access denied. You do not have permission to view or download this document.",
          code: "UNAUTHORIZED_DOCUMENT_ACCESS",
        });
      }
    }

    // Check if the physical file exists on disk
    if (!fs.existsSync(targetPath) || !fs.statSync(targetPath).isFile()) {
      return res.status(404).json({
        success: false,
        message: `Document file '${safeFilename}' not found on storage server.`,
      });
    }

    // Security & content disposition headers
    res.setHeader("X-Content-Type-Options", "nosniff");
    res.setHeader("Cache-Control", "private, no-cache, no-store, must-revalidate");

    const isDownload = req.query.download === "true" || req.query.download === "1";
    res.setHeader(
      "Content-Disposition",
      `${isDownload ? "attachment" : "inline"}; filename="${safeFilename}"`
    );

    return res.sendFile(targetPath, (err) => {
      if (err && !res.headersSent) {
        return res.status(500).json({
          success: false,
          message: "Failed to transmit document file.",
        });
      }
    });
  } catch (error) {
    console.error("serveSecureDocument error:", error);
    return res.status(500).json({
      success: false,
      message: "Internal server error while retrieving document",
      error: error.message,
    });
  }
};
